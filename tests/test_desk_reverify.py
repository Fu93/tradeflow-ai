def test_mailbox_errors_are_502_and_gmail_pages(tmp_path, monkeypatch):
    from fastapi.testclient import TestClient

    from src.app.main import app
    from src.desk import mailbox
    from src.desk.mailbox import MailboxError
    from src.desk.store import reset_stores

    monkeypatch.setenv("TRADEFLOW_DESK_DB", str(tmp_path / "desk.db"))
    monkeypatch.setenv("TRADEFLOW_ENV", "sandbox")
    monkeypatch.setenv("TRADEFLOW_API_KEY", "desk-reverify-key")
    monkeypatch.setenv("DESK_N_SAMPLES", "40")
    monkeypatch.setenv("DESK_N_GRID", "8")
    reset_stores()
    client = TestClient(app)
    headers = {"X-API-Key": "desk-reverify-key"}
    created = client.post(
        "/api/v1/desk/deals",
        json={
            "product": "umbrella",
            "quantity": 1000,
            "target_price": 12,
            "ceiling_price": 20,
            "risk_tolerance": 0.5,
            "suppliers": [
                {"name": "Ningbo", "address": "ningbo@example.test"},
                {"name": "Wenzhou", "address": "wenzhou@example.test"},
                {"name": "Yiwu", "address": "yiwu@example.test"},
                {"name": "Foshan", "address": "foshan@example.test"},
            ],
        },
        headers=headers,
    )
    assert created.status_code == 200, created.text
    deal_id = created.json()["deal"]["id"]
    denied = client.get(f"/api/v1/desk/deals/{deal_id}/stream")
    assert denied.status_code == 401

    def boom(**_kwargs):
        raise MailboxError("The mail server certificate could not be verified.")

    monkeypatch.setenv("IMAP_HOST", "imap.example.test")
    monkeypatch.setenv("IMAP_USERNAME", "desk")
    monkeypatch.setenv("IMAP_PASSWORD", "desk")
    monkeypatch.setattr("src.desk.service.mailbox.pull_window", boom)
    response = client.post("/api/v1/desk/poll", json={"channel": "imap"}, headers=headers)
    assert response.status_code == 502
    assert "certificate" in response.json()["detail"]

    def tls(**_kwargs):
        raise ssl.SSLError("certificate verify failed")

    monkeypatch.setattr("src.desk.service.mailbox.pull_window", tls)
    tls_response = client.post("/api/v1/desk/poll", json={"channel": "imap"}, headers=headers)
    assert tls_response.status_code == 502

    pages = {"n": 0}

    class _Response:
        def __init__(self, body: bytes):
            self._body = body

        def read(self):
            return self._body

        def __enter__(self):
            return self

        def __exit__(self, *_args):
            return False

    class _Opener:
        def open(self, request, timeout=None):
            pages["n"] += 1
            if pages["n"] == 1:
                body = json.dumps({"messages": [{"id": "m1"}], "nextPageToken": "next"}).encode()
            else:
                body = json.dumps({"messages": [{"id": "m2"}]}).encode()
            return _Response(body)

    ids = mailbox.gmail_list_recent(_Opener(), "token")
    assert ids == ["m1", "m2"]
    reset_stores()


