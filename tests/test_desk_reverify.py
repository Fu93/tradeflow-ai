def test_snap_to_grid_does_not_raise_when_a_rival_improves():
    from src.engine.coupled import solve_coupled

    rng = np.random.default_rng(11)
    rises = 0
    checked = 0
    worst = 0.0
    for _step in range(80):
        target = 28.0
        own = float(rng.uniform(22.0, 40.0))
        rival = float(rng.uniform(own, 50.0))
        improved = float(rng.uniform(18.0, rival))
        ceiling = 52.0 / target
        means = np.array([1.05, 1.05])
        stds = np.array([0.08, 0.08])
        seed = int(rng.integers(0, 10000))
        before = solve_coupled(
            np.array([own / target, rival / target]),
            means,
            stds,
            ceiling=ceiling,
            n_samples=40,
            n_grid=20,
            rng=np.random.default_rng(seed),
            snap_to_grid=True,
        )
        after = solve_coupled(
            np.array([own / target, improved / target]),
            means,
            stds,
            ceiling=ceiling,
            n_samples=40,
            n_grid=20,
            rng=np.random.default_rng(seed),
            snap_to_grid=True,
        )
        if before["blocked"][0] or after["blocked"][0]:
            continue
        checked += 1
        delta = float(after["offers"][0] - before["offers"][0])
        worst = max(worst, delta)
        if delta > 1e-8:
            rises += 1
    assert checked > 20
    assert rises == 0, worst


def test_mail_is_not_consumed_before_it_can_be_routed(tmp_path, monkeypatch):
    from src.desk.service import create_deal, poll_imap_once
    from src.desk.store import DeskStore
    from tests.imap_fixture import ImapFixture

    fixture = ImapFixture()
    monkeypatch.setenv("IMAP_HOST", "127.0.0.1")
    monkeypatch.setenv("IMAP_PORT", str(fixture.port))
    monkeypatch.setenv("IMAP_USERNAME", "desk")
    monkeypatch.setenv("IMAP_PASSWORD", "desk")
    monkeypatch.setenv("IMAP_SSL", "0")
    monkeypatch.setenv("DESK_N_SAMPLES", "40")
    monkeypatch.setenv("DESK_N_GRID", "8")
    store = DeskStore(str(tmp_path / "desk.db"))
    suppliers = [
        {"name": "Ningbo", "address": "ningbo@example.test"},
        {"name": "Wenzhou", "address": "wenzhou@example.test"},
        {"name": "Yiwu", "address": "yiwu@example.test"},
        {"name": "Foshan", "address": "foshan@example.test"},
    ]
    try:
        fixture.append((FIXTURES / "ningbo.eml").read_bytes())
        early = poll_imap_once(store)
        assert early["status"] == "no-deals"
        first = create_deal(
            store,
            product="umbrella",
            quantity=1000,
            target_price=12,
            ceiling_price=20,
            risk_tolerance=0.5,
            seed=11,
            suppliers=suppliers,
        )
        deal_a = first["deal"]["id"]
        ingested = poll_imap_once(store, deal_id=deal_a)
        assert ingested["ingested"] == 1
        second = create_deal(
            store,
            product="umbrella",
            quantity=1000,
            target_price=12,
            ceiling_price=20,
            risk_tolerance=0.5,
            seed=12,
            suppliers=suppliers,
        )
        deal_b = second["deal"]["id"]
        fixture.append((FIXTURES / "wenzhou.eml").read_bytes())
        scoped = poll_imap_once(store, deal_id=deal_a)
        assert scoped["ingested"] == 1
        other = poll_imap_once(store, deal_id=deal_b)
        assert other["ingested"] >= 1
        routed = store.events(deal_b)
        assert routed
        assert any(event["provenance"].get("origin") == "fixture" for event in routed)
        assert any(event["status"] == "review" for event in routed)
        fixture.append((FIXTURES / "unknown.eml").read_bytes())
        ignored = poll_imap_once(store, deal_id=deal_a)
        assert ignored["ignored"] >= 1
        seen = store.mailbox_ids(f"imap:127.0.0.1:desk:{deal_a}")
        assert not any("stranger" in item for item in seen)
        assert all("<unknown" not in item for item in seen)
    finally:
        fixture.close()
        store.close()


def test_withheld_counter_and_sent_draft_are_not_sent_again(tmp_path, monkeypatch):
    from src.desk.recompute import recompute
    from src.desk.service import DraftStale, create_deal, deal_lock, draft_digest, ingest_message, send_draft
    from src.desk.store import DeskStore
    from src.engine.coupled import solve_coupled

    monkeypatch.setenv("DESK_N_SAMPLES", "40")
    monkeypatch.setenv("DESK_N_GRID", "8")
    store = DeskStore(str(tmp_path / "desk.db"))
    snapshot = create_deal(
        store,
        product="umbrella",
        quantity=1000,
        target_price=12,
        ceiling_price=20,
        risk_tolerance=0.5,
        seed=11,
        suppliers=[
            {"name": "Ningbo", "address": "ningbo@example.test"},
            {"name": "Wenzhou", "address": "wenzhou@example.test"},
            {"name": "Yiwu", "address": "yiwu@example.test"},
            {"name": "Foshan", "address": "foshan@example.test"},
        ],
    )
    deal_id = snapshot["deal"]["id"]
    store.set_policy(deal_id, {"expected_markup": 0.08})
    ningbo = snapshot["suppliers"][0]["id"]
    ingest_message(
        store,
        deal_id,
        source="paste",
        raw_text="单价 15.60 元",
        supplier_id=ningbo,
        external_id="<hold@example.test>",
        provenance_extra={"message_id": "<a1@ningbo.test>", "references": "<rfq-1@example.test> <rfq-2@example.test>"},
    )
    draft = next(item for item in store.drafts(deal_id) if item["status"] == "draft")
    header = draft["references_header"] or ""
    assert "<rfq-1@example.test>" in header
    assert "<rfq-2@example.test>" in header
    assert "<a1@ningbo.test>" in header
    calls = []
    held = []

    async def spy(*_args, **_kwargs):
        held.append(deal_lock(deal_id).locked())
        calls.append(1)
        await asyncio.sleep(0.02)
        return True

    monkeypatch.setenv("DESK_SMTP_SEND", "1")
    monkeypatch.setenv("SMTP_HOST", "smtp.example.test")
    monkeypatch.setenv("EMAIL_USERNAME", "buyer@example.test")
    monkeypatch.setenv("EMAIL_PASSWORD", "desk-secret")
    digest = draft_digest(draft["body"])

    async def twice():
        return await asyncio.gather(
            send_draft(store, draft["id"], human_approved=True, body_sha256=digest, sender=spy),
            send_draft(store, draft["id"], human_approved=True, body_sha256=digest, sender=spy),
            return_exceptions=True,
        )

    results = asyncio.run(twice())
    assert calls == [1]
    assert held == [False]
    assert any(not isinstance(item, Exception) and item["status"] == "sent" for item in results)
    assert any(isinstance(item, DraftStale) for item in results)
    recompute(store, deal_id)
    assert not any(item["status"] == "draft" and item["body"] == draft["body"] for item in store.drafts(deal_id))
    again = asyncio.run(send_draft(store, draft["id"], human_approved=True, body_sha256=digest, sender=spy))
    assert again["status"] == "sent"
    assert calls == [1]

    def blocked(*args, **kwargs):
        solved = solve_coupled(*args, **kwargs)
        solved["blocked"] = [True for _item in solved["blocked"]]
        return solved

    monkeypatch.setattr("src.desk.recompute.solve_coupled", blocked)
    ingest_message(
        store,
        deal_id,
        source="paste",
        raw_text="单价 14.40 元",
        supplier_id=ningbo,
        external_id="<held-2@example.test>",
    )
    fresh = [item for item in store.drafts(deal_id) if item["supplier_id"] == ningbo and item["status"] == "draft"]
    assert fresh == []
    store.close()


