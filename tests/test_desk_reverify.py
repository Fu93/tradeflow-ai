def _corpus():
    namespace: dict = {}
    exec((ROOT / "tests" / "fixtures" / "quote_corpus.py").read_text(encoding="utf-8"), namespace)
    return namespace["C"]


def test_verifier_corpus_accepts_only_one_cny_unit_price():
    from src.desk.parse import parse_quote

    rows = _corpus()
    true_positive = false_positive = false_negative = 0
    for name, text, expect in rows:
        parsed = parse_quote(text)
        price = parsed["parsed"]["unit_price"]
        if expect is None:
            if parsed["status"] == "accepted":
                false_positive += 1
                pytest.fail(f"{name} was accepted at {price}")
        elif parsed["status"] == "accepted" and abs(float(price) - float(expect)) < 1e-6:
            true_positive += 1
        else:
            false_negative += 1
            pytest.fail(f"{name} expected {expect} got {price} {parsed['provenance'].get('review_reason')}")
    accepted = sum(1 for _name, _text, expect in rows if expect is not None)
    assert true_positive == accepted
    assert false_positive == 0
    assert false_negative == 0
    precision = true_positive / (true_positive + false_positive)
    assert precision == 1


def test_held_out_quotes_follow_the_same_rules():
    from src.desk.parse import parse_quote, price_from_token

    for name, text, expect in HELD_OUT:
        parsed = parse_quote(text)
        price = parsed["parsed"]["unit_price"]
        if expect is None:
            assert parsed["status"] == "review", name
        else:
            assert parsed["status"] == "accepted", name
            assert abs(float(price) - float(expect)) < 1e-6
    usd = "Unit price: 4.60 USD per piece, FOB Shenzhen."
    assert price_from_token(usd, "4.60") is None
    assert price_from_token("Unit price: 33.80 CNY/pc.", "33.80") == pytest.approx(33.80)


def test_auction_keeps_the_off_grid_cap_and_the_desk_drops_it():
    from src.config.heuristics import OFFER_GRID_FLOOR
    from src.engine.coupled import _candidates, _master_grid

    grid = _master_grid(float(OFFER_GRID_FLOOR), 1.4, 20)
    hi = float((grid[3] + grid[4]) / 2)
    auction = _candidates(grid, hi, snap_to_grid=False)
