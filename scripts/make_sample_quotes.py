#!/usr/bin/env python3
"""Write three labeled simulation quote screenshots and their transcripts.

The pictures are drawn in this repository. They are not factory chats.
Each PNG carries a tEXt comment that says SIMULATION, and the sibling .txt
is the transcript the desk sends to the reader. Selecting a sample does not
claim that a vision model OCRed the pixels.

    python scripts/make_sample_quotes.py
"""
from __future__ import annotations

import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "web" / "static" / "samples"

SAMPLES = (
    (
        "quote_01",
        "Umbrella chat (simulation)",
        "SIMULATION — not a real supplier screenshot.\n单价：14.80元。5000個。21天。30%定金。\n",
    ),
    (
        "quote_02",
        "CNC case chat (simulation)",
        "SIMULATION — not a real supplier screenshot.\n報價：28.50元。2000 pcs。18 days。20%定金。\n",
    ),
    (
        "quote_03",
        "Battery pack chat (simulation)",
        "SIMULATION — not a real supplier screenshot.\n價格：190.00元。500套。45天。40%預付。\n",
    ),
)

COMMENT = "SIMULATION not a real supplier screenshot. Generated by scripts/make_sample_quotes.py."


def _chunk(tag: bytes, data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)


def _png(width: int, height: int, rgb: bytes, comment: str) -> bytes:
    raw = b"".join(b"\x00" + rgb[y * width * 3 : (y + 1) * width * 3] for y in range(height))
    ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    text = b"Comment\x00" + comment.encode("latin-1", errors="replace")
    return b"\x89PNG\r\n\x1a\n" + _chunk(b"IHDR", ihdr) + _chunk(b"tEXt", text) + _chunk(b"IDAT", zlib.compress(raw, 9)) + _chunk(b"IEND", b"")


def _draw(title: str, body: str) -> bytes:
    from PIL import Image, ImageDraw, ImageFont

    width, height = 880, 520
    image = Image.new("RGB", (width, height), (251, 247, 240))
    draw = ImageDraw.Draw(image)
    draw.rectangle((0, 0, width, 72), fill=(30, 58, 76))
    font = ImageFont.load_default()
    draw.text((24, 24), "SIMULATION — not a real supplier screenshot", fill=(251, 247, 240), font=font)
    draw.text((24, 100), title, fill=(28, 23, 18), font=font)
    y = 150
    for line in body.splitlines():
        draw.text((24, y), line, fill=(28, 23, 18), font=font)
        y += 28
    draw.text((24, height - 48), "Generated in-repo. Not a factory chat.", fill=(90, 78, 66), font=font)
    raw = image.tobytes()
    return _png(width, height, raw, COMMENT)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, title, body in SAMPLES:
        (OUT / f"{name}.txt").write_text(body, encoding="utf-8")
        (OUT / f"{name}.png").write_bytes(_draw(title, body))
        print(f"wrote {name}.png and {name}.txt")


if __name__ == "__main__":
    main()
